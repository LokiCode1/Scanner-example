class NarrowingLong 

{
	public static void main(String[] args) 
	{

		long c = 12121212l;
		int d = (int)c;
		short e = (short)c;
		char f =(char)c;
		byte g = (byte)c;
		
		System.out.println(c);
		System.out.println(d);
		System.out.println(e);
		System.out.println(f);
		System.out.println(g);
		
	}   
}
