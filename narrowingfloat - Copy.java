class NarrowingFloat 

{
	public static void main(String[] args) 
	{
		float b = 1.5654f;
		long c = (long)b;
		int d = (int)b;
		short e = (short)b;
		char f =(char)b;
		byte g = (byte)b;
		System.out.println(b);
		System.out.println(c);
		System.out.println(d);
		System.out.println(e);
		System.out.println(f);
		System.out.println(g);
		
	}   
}
